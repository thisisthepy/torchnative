"""The vendored ExecuTorch subset is exactly what its manifest says (issue #312, step R0).

`torchnative/rust/vendor/executorch/` is generated by
`scripts/vendor/vendor_executorch.py` from ExecuTorch v1.4.1 (commit e4d02f41)
and committed, with a `MANIFEST.tsv` of every file's sha256. Vendoring it, and
shipping the whole portable kernel library rather than an allow-list, are the
leader's decisions of 2026-11-14; the design they implement is an agent
proposal, not confirmed.

What this suite checks:

  * `--check` passes on the committed tree, with no ExecuTorch checkout;
  * a copy with one byte changed, a copy with an extra file and a copy with a
    missing file are each reported red, by file name (AGENTS.md §17.5: the
    check is made to fail on purpose);
  * a checkout at another commit is refused by name, before anything is written;
  * the generated op list covers exactly the ops of the vendored functions.yaml;
  * with `TORCHNATIVE_ET_SRC` pointing at a v1.4.1 checkout (and flatc 24.3.25
    plus torchgen from torch 2.13.0 available to the script), the tree is
    regenerated and compared byte for byte. Without one, that test is a SKIP
    by name: CI has no checkout, and nothing here downloads one.

What this suite cannot find: whether the tree compiles and links. That is step
R1, in CI. It also cannot tell a hand edit from a regeneration when the edit
also rewrote MANIFEST.tsv; only the byte-for-byte regeneration (local, with a
checkout) or review of the diff can.
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

REPO = next(p for p in pathlib.Path(__file__).resolve().parents if (p / "AGENTS.md").is_file())
sys.path.insert(0, str(REPO / "tests" / "_support"))
import _skip  # noqa: E402

SCRIPT = REPO / "scripts" / "vendor" / "vendor_executorch.py"
TREE = REPO / "torchnative" / "rust" / "vendor" / "executorch"
COMMIT = "e4d02f41f7909e8ed5bf4a14ffc520d733453d9f"


def _run(*args, env=None):
    done = subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True,
                          env=env)
    return done.returncode, done.stdout + done.stderr


def _scratch_base():
    """Temporary copies live in the repository's git-ignored .scratch/ (AGENTS.md §2)."""
    base = REPO / ".scratch"
    base.mkdir(exist_ok=True)
    return str(base)


def _tampered(edit):
    """Run --check on a copy of the tree after `edit(copy)`; return (rc, output)."""
    work = tempfile.mkdtemp(prefix="test_executorch_vendor-", dir=_scratch_base())
    try:
        copy = pathlib.Path(work) / "executorch"
        shutil.copytree(TREE, copy)
        edit(copy)
        return _run("--check", "--dest", str(copy))
    finally:
        shutil.rmtree(work)


def test_check_passes_on_the_committed_tree():
    assert TREE.is_dir(), f"{TREE} does not exist: run scripts/vendor/vendor_executorch.py --source <checkout>"
    rc, out = _run("--check")
    assert rc == 0, f"--check failed on the committed tree:\n{out}"
    m = re.search(r": (\d+) files, (\d+) bytes match MANIFEST.tsv", out)
    assert m and int(m.group(1)) > 300, f"--check passed but counted too little:\n{out}"
    for group in ("core", "prim_ops", "portable", "headers", "generated", "license"):
        assert re.search(rf"^\s+{group}\s+[1-9]\d* files", out, re.M), f"no {group} files:\n{out}"


def test_one_changed_byte_is_reported_by_name():
    victim = "runtime/executor/method.cpp"

    def flip(copy):
        p = copy / victim
        data = bytearray(p.read_bytes())
        data[len(data) // 2] ^= 0x01
        p.write_bytes(bytes(data))

    rc, out = _tampered(flip)
    assert rc == 1, f"a changed byte passed --check (rc {rc}):\n{out}"
    assert f"modified: {victim}" in out, out
    assert out.count("modified:") == 1, out


def test_an_extra_file_is_reported_by_name():
    rc, out = _tampered(lambda copy: (copy / "kernels/portable/cpu/op_stray.cpp").write_text("int x;\n"))
    assert rc == 1, f"an extra file passed --check (rc {rc}):\n{out}"
    assert "extra: kernels/portable/cpu/op_stray.cpp" in out, out


def test_a_missing_file_is_reported_by_name():
    victim = "generated/include/executorch/schema/program_generated.h"
    rc, out = _tampered(lambda copy: (copy / victim).unlink())
    assert rc == 1, f"a missing file passed --check (rc {rc}):\n{out}"
    assert f"missing: {victim}" in out, out


def test_a_missing_manifest_is_reported():
    rc, out = _tampered(lambda copy: (copy / "MANIFEST.tsv").unlink())
    assert rc == 1, out
    assert "missing: MANIFEST.tsv" in out, out


def test_a_checkout_at_another_commit_is_refused_by_name():
    work = tempfile.mkdtemp(prefix="test_executorch_vendor-", dir=_scratch_base())
    try:
        fake = pathlib.Path(work) / "et"
        (fake / "shim_et/xplat/executorch/build").mkdir(parents=True)
        (fake / "shim_et/xplat/executorch/build/build_variables.bzl").write_text("X = []\n")
        git = ["git", "-C", str(fake), "-c", "user.name=t", "-c", "user.email=t@t"]
        for cmd in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", "not v1.4.1"]):
            subprocess.run(git + cmd, check=True, capture_output=True)
        dest = pathlib.Path(work) / "out"
        rc, out = _run("--source", str(fake), "--dest", str(dest), "--scratch", work)
        assert rc == 2, f"a wrong commit was not refused (rc {rc}):\n{out}"
        assert "refusing" in out and COMMIT in out and "not ExecuTorch v1.4.1" in out, out
        assert not dest.exists(), "the refusal wrote the destination"
    finally:
        shutil.rmtree(work)


_YAML_OP = r"^- (?:op|func): ([A-Za-z0-9_]+(?:::[A-Za-z0-9_]+)?\.?[A-Za-z0-9_]*)"


def _qualified(names):
    """functions.yaml leaves `aten::` implicit; the generated files spell it."""
    return {n if "::" in n else f"aten::{n}" for n in names}


def _ops(text, pattern):
    return set(re.findall(pattern, text, re.M))


def test_the_generated_registrations_cover_every_portable_op():
    functions = (TREE / "kernels/portable/functions.yaml").read_text()
    entries = re.findall(_YAML_OP, functions, re.M)
    wanted = _qualified(entries)
    assert len(entries) == len(wanted) == 209, (
        f"functions.yaml has {len(entries)} entries, {len(wanted)} distinct; the design counted 209")
    selected = (TREE / "generated/portable_ops_lib/selected_operators.yaml").read_text()
    listed = _ops(selected, r"^  ([a-z_]+::[A-Za-z0-9_.]+):$")
    assert listed == wanted, (
        f"selected_operators.yaml differs from functions.yaml: only in yaml "
        f"{sorted(wanted - listed)[:5]}, only in selection {sorted(listed - wanted)[:5]}")
    register = (TREE / "generated/portable_ops_lib/RegisterCodegenUnboxedKernelsEverything.cpp").read_text()
    registered = _ops(register, r'"([a-z_]+::[A-Za-z0-9_.]+)"')
    assert registered == wanted, (
        f"registrations differ from functions.yaml: unregistered {sorted(wanted - registered)[:5]}, "
        f"unexpected {sorted(registered - wanted)[:5]}")


def test_the_op_coverage_check_can_fail():
    text = "- op: add.out\n- func: mul.out(Tensor self)\n- func: et_copy::_h2d_copy.out(Tensor self)\n#- op: x.out\n"
    assert _qualified(re.findall(_YAML_OP, text, re.M)) == {
        "aten::add.out", "aten::mul.out", "et_copy::_h2d_copy.out"}
    assert _ops('Kernel("aten::add.out", ...)', r'"([a-z_]+::[A-Za-z0-9_.]+)"') == {"aten::add.out"}


def test_regenerates_byte_for_byte_from_a_source_checkout():
    import os
    src = os.environ.get("TORCHNATIVE_ET_SRC")
    if not src:
        _skip.skip("TORCHNATIVE_ET_SRC is not set: no ExecuTorch v1.4.1 checkout to regenerate from")
        return
    rc, out = _run("--check", "--source", src)
    assert rc == 0, f"regeneration differs from the committed tree:\n{out}"
    assert "byte for byte" in out, out


def _main():
    items = [(name, fn) for name, fn in sorted(globals().items()) if name.startswith("test_")]
    failures = _skip.run_tests(items, suite="test_executorch_vendor")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(_main())
