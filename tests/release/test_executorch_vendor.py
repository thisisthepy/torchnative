_YAML_OP = r"^- (?:op|func): ([A-Za-z0-9_]+(?:::[A-Za-z0-9_]+)?\.?[A-Za-z0-9_]*)"


def _qualified(names):
    """functions.yaml leaves `aten::` implicit; the generated files spell it."""
    return {n if "::" in n else f"aten::{n}" for n in names}


def _ops(text, pattern):
    return set(re.findall(pattern, text, re.M))


def test_the_generated_registrations_cover_every_portable_op():
    functions = (TREE / "kernels/portable/functions.yaml").read_text()
    entries = re.findall(_YAML_OP, functions, re.M)
    wanted = _qualified(entries)
    assert len(entries) == len(wanted) == 209, (
        f"functions.yaml has {len(entries)} entries, {len(wanted)} distinct; the design counted 209")
    selected = (TREE / "generated/portable_ops_lib/selected_operators.yaml").read_text()
    listed = _ops(selected, r"^  ([a-z_]+::[A-Za-z0-9_.]+):$")
    assert listed == wanted, (
        f"selected_operators.yaml differs from functions.yaml: only in yaml "
        f"{sorted(wanted - listed)[:5]}, only in selection {sorted(listed - wanted)[:5]}")
    register = (TREE / "generated/portable_ops_lib/RegisterCodegenUnboxedKernelsEverything.cpp").read_text()
    registered = _ops(register, r'"([a-z_]+::[A-Za-z0-9_.]+)"')
    assert registered == wanted, (
        f"registrations differ from functions.yaml: unregistered {sorted(wanted - registered)[:5]}, "
        f"unexpected {sorted(registered - wanted)[:5]}")


def test_the_op_coverage_check_can_fail():
    text = "- op: add.out\n- func: mul.out(Tensor self)\n- func: et_copy::_h2d_copy.out(Tensor self)\n#- op: x.out\n"
    assert _qualified(re.findall(_YAML_OP, text, re.M)) == {
        "aten::add.out", "aten::mul.out", "et_copy::_h2d_copy.out"}
    assert _ops('Kernel("aten::add.out", ...)', r'"([a-z_]+::[A-Za-z0-9_.]+)"') == {"aten::add.out"}


